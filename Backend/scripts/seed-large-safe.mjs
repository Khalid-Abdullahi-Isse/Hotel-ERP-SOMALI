import 'dotenv/config';
import { Pool } from 'pg';

const databaseUrl = process.env.DATABASE_URL;
if (!databaseUrl) throw new Error('DATABASE_URL is required.');

const hotelCode = argument('--hotel-code')?.trim().toUpperCase();
const requestedRecords = Number(argument('--records') ?? '100000');

if (!hotelCode || !/^[A-Z0-9_-]{2,32}$/.test(hotelCode)) {
  throw new Error('--hotel-code is required and must contain only letters, numbers, _ or -.');
}
if (!Number.isSafeInteger(requestedRecords) || requestedRecords < 1 || requestedRecords > 1_000_000) {
  throw new Error('--records must be an integer between 1 and 1,000,000.');
}

const seedKey = `safe-seed-${hotelCode.toLowerCase()}`;
const pool = new Pool({ connectionString: databaseUrl });
const client = await pool.connect();

try {
  await client.query('BEGIN');

  const target = await client.query(
    `SELECT h.id, h.code, h.name,
       (SELECT count(DISTINCT u.id)::int
        FROM "User" u
        JOIN "UserRole" ur ON ur."userId" = u.id
        JOIN "Role" r ON r.id = ur."roleId"
        WHERE u."hotelId" = h.id AND u.status = 'ACTIVE' AND u."deletedAt" IS NULL
          AND r.name = 'ADMIN' AND r."isSystem" = true AND r."isActive" = true
       ) AS active_admins
     FROM "Hotel" h
     WHERE h.code = $1 AND h."isActive" = true
     FOR UPDATE OF h`,
    [hotelCode],
  );

  if (target.rowCount !== 1) throw new Error(`Active hotel ${hotelCode} was not found.`);
  if (target.rows[0].active_admins < 1) {
    throw new Error(`Hotel ${hotelCode} has no active system administrator; refusing to seed.`);
  }

  const existing = await client.query(
    `SELECT count(*)::int AS count
     FROM "Guest"
     WHERE "hotelId" = $1 AND "normalizedEmail" LIKE $2`,
    [target.rows[0].id, `${seedKey}.%@example.invalid`],
  );
  if (existing.rows[0].count > 0) {
    throw new Error(
      `Seed marker already exists for ${hotelCode} (${existing.rows[0].count} rows); refusing to duplicate it.`,
    );
  }

  const before = await protectedCounts(client, target.rows[0].id);
  const inserted = await client.query(
    `INSERT INTO "Guest" (
       id, "hotelId", "fullName", phone, "normalizedPhone", email, "normalizedEmail",
       "passportNumber", "nationalId", nationality, address, notes, "createdAt", "updatedAt"
     )
     SELECT
       gen_random_uuid(), $1::uuid,
       first_names[((n - 1) % array_length(first_names, 1)) + 1] || ' ' ||
         last_names[((n * 7 - 1) % array_length(last_names, 1)) + 1],
       '+25267' || lpad(n::text, 7, '0'),
       '+25267' || lpad(n::text, 7, '0'),
       $2 || '.' || lpad(n::text, 6, '0') || '@example.invalid',
       $2 || '.' || lpad(n::text, 6, '0') || '@example.invalid',
       CASE WHEN n % 3 = 0 THEN 'SP-' || lpad(n::text, 9, '0') END,
       CASE WHEN n % 3 <> 0 THEN 'SN-' || lpad(n::text, 9, '0') END,
       nationalities[((n * 3 - 1) % array_length(nationalities, 1)) + 1],
       cities[((n - 1) % array_length(cities, 1)) + 1],
       CASE WHEN n % 19 = 0 THEN 'Generated by the additive large-data seed.' END,
       now() - (n % 730) * interval '1 day', now()
     FROM generate_series(1, $3::int) AS series(n)
     CROSS JOIN LATERAL (SELECT ARRAY[
       'Ahmed','Mohamed','Abdi','Hassan','Yusuf','Ibrahim','Omar','Ali',
       'Khalid','Mustafa','Amina','Fadumo','Hodan','Sahra','Maryan','Nasteho'
     ]::text[] AS first_names) firsts
     CROSS JOIN LATERAL (SELECT ARRAY[
       'Abdullahi','Warsame','Jama','Nur','Ismail','Farah','Osman','Aden',
       'Hussein','Mire','Roble','Dahir'
     ]::text[] AS last_names) lasts
     CROSS JOIN LATERAL (SELECT ARRAY[
       'Somalia','Kenya','Ethiopia','Djibouti','United Kingdom',
       'United States','United Arab Emirates','Turkey','Qatar','Sweden'
     ]::text[] AS nationalities) nations
     CROSS JOIN LATERAL (SELECT ARRAY[
       'Mogadishu','Hargeisa','Nairobi','Addis Ababa',
       'Djibouti City','Dubai','London','Stockholm'
     ]::text[] AS cities) locations`,
    [target.rows[0].id, seedKey, requestedRecords],
  );

  if (inserted.rowCount !== requestedRecords) {
    throw new Error(`Expected ${requestedRecords} inserts but PostgreSQL reported ${inserted.rowCount}.`);
  }

  const after = await protectedCounts(client, target.rows[0].id);
  if (after.users !== before.users || after.admins !== before.admins) {
    throw new Error('Protected user or administrator counts changed; rolling back the seed.');
  }

  await client.query('COMMIT');
  console.log(
    JSON.stringify({
      hotel: { code: target.rows[0].code, name: target.rows[0].name },
      insertedGuests: inserted.rowCount,
      totalGuests: after.guests,
      preservedUsers: after.users,
      preservedAdmins: after.admins,
    }),
  );
} catch (error) {
  await client.query('ROLLBACK');
  throw error;
} finally {
  client.release();
  await pool.end();
}

function argument(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

async function protectedCounts(database, hotelId) {
  const result = await database.query(
    `SELECT
       (SELECT count(*)::int FROM "Guest" WHERE "hotelId" = $1) AS guests,
       (SELECT count(*)::int FROM "User" WHERE "hotelId" = $1) AS users,
       (SELECT count(DISTINCT u.id)::int
        FROM "User" u
        JOIN "UserRole" ur ON ur."userId" = u.id
        JOIN "Role" r ON r.id = ur."roleId"
        WHERE u."hotelId" = $1 AND u.status = 'ACTIVE' AND u."deletedAt" IS NULL
          AND r.name = 'ADMIN' AND r."isSystem" = true AND r."isActive" = true) AS admins`,
    [hotelId],
  );
  return result.rows[0];
}
